"""Builds app/src/main/assets/art/sprites.txt from the portrait/sprite sources.
Run:  cd tools && python3 gen_sprites.py
Each sprite in the output is:  '== name W H' followed by H rows ('.'=clear, 0-3 shade)."""
import os
from expr import build
from small import S
out = dict(build()); out.update(S)
path = os.path.join(os.path.dirname(__file__), '..','app','src','main','assets','art','sprites.txt')
with open(path,'w') as f:
    f.write('# Reese sprite sheet. Shades: . clear, 0 lightest .. 3 darkest. Generated by tools/gen_sprites.py\n')
    for k,v in out.items():
        f.write(f'== {k} {len(v[0])} {len(v)}\n' + '\n'.join(v) + '\n')
print(len(out),'sprites ->',os.path.normpath(path))
