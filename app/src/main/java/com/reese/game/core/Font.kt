    init {
        for ((ch, data) in src) glyphs[ch] = Sprite.parse(data.split(' ').map { it.replace('#', '3') })
    }

    private fun clean(c: Char): Char = when (c) {
        '’', '‘' -> '\''
        '“', '”' -> '"'
        '—', '–' -> '-'
        else -> c
    }

    fun advance(c: Char): Int {
        if (c == ' ') return 3
        val g = glyphs[clean(c)] ?: glyphs['?']!!
        return g.w + 1
    }

    fun width(s: String): Int {
        var w = 0
        for (c in s.replace("…", "...")) w += advance(c)
        return if (w > 0) w - 1 else 0
    }

    fun draw(scr: Scr, s0: String, x: Int, y: Int, color: Int): Int {
        var cx = x
        for (c0 in s0.replace("…", "...")) {
            if (c0 == ' ') { cx += 3; continue }
            val c = clean(c0)
            val g = glyphs[c] ?: glyphs['?']!!
            for (j in 0 until g.h) for (i in 0 until g.w) if (g.px[j * g.w + i] >= 0) scr.pset(cx + i, y + j, color)
            cx += g.w + 1
        }
        return cx
    }

    fun drawScaled(scr: Scr, s: String, x: Int, y: Int, k: Int, color: Int): Int {
        var cx = x
        for (c0 in s) {
            if (c0 == ' ') { cx += 3 * k; continue }
            val g = glyphs[clean(c0)] ?: glyphs['?']!!
            for (j in 0 until g.h) for (i in 0 until g.w) if (g.px[j * g.w + i] >= 0) scr.rect(cx + i * k, y + j * k, k, k, color)
            cx += (g.w + 1) * k
        }
        return cx
    }

    /** Word-wrap to a pixel width. Honors explicit '\n'. */
    fun wrap(s: String, maxW: Int): List<String> {
        val out = ArrayList<String>()
        for (para in s.split('\n')) {
            var line = ""
            for (word in para.split(' ')) {
                val cand = if (line.isEmpty()) word else "$line $word"
                if (width(cand) <= maxW || line.isEmpty()) line = cand
                else { out.add(line); line = word }
            }
            out.add(line)
        }
        return out
    }
